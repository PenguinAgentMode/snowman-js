// gen-id.mjs: generate src/unicode/id_tables.inc from node's own Unicode data (process.versions.unicode).
//   node tools/unicode/gen-id.mjs > src/unicode/id_tables.inc
const ranges = (re) => {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const hit = cp < 0x110000 && re.test(String.fromCodePoint(cp));
    if (hit && start < 0) start = cp;
    if (!hit && start >= 0) {
      out.push([start, cp - 1]);
      start = -1;
    }
  }
  return out;
};
const table = (name, re) => {
  const rs = ranges(re);
  const body = rs.map(([a, b]) => `{0x${a.toString(16)}, 0x${b.toString(16)}}`).join(',\n  ');
  return `static constexpr Range ${name}[] = {\n  ${body}\n};\n`;
};
console.log(`// Generated by tools/unicode/gen-id.mjs from Unicode ${process.versions.unicode}. Do not edit.`);
