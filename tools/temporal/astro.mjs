//
// From Jean Meeus, "Astronomical Algorithms", 2nd ed. (1998):
// - newMoon(k): chapter 49, the mean lunation plus the New Moon periodic terms and the 14 planetary arguments
//   (Meeus: error below ~20 s against ELP-2000/82 near 2000);
// - sunLongitude(jde): the Sun's apparent longitude from VSOP87 Earth L and R as abridged in Appendix III
//   (chapters 25 and 32), the FK5 correction (25.9), nutation in longitude from the four largest terms of
//   chapter 22 (0.5") and aberration (25.10);
// - deltaT(year): TT - UT, the Espenak & Meeus polynomials ("Five Millennium Canon of Solar Eclipses", NASA 2006).
// Times are Julian Ephemeris Days (TT) unless the name says ut.
const D2R = Math.PI / 180;
const J2000 = 2451545.0;
const sinD = (x) => Math.sin(x * D2R);

// TT - UT in seconds at a decimal year.
export function deltaT(y) {
  let t;
  if (y < 1800) { const u = (y - 1820) / 100; return -20 + 32 * u * u; }
  if (y < 1860) {
    t = y - 1800;
    return 13.72 - 0.332447 * t + 0.0068612 * t ** 2 + 0.0041116 * t ** 3 - 0.00037436 * t ** 4 +
      0.0000121272 * t ** 5 - 0.0000001699 * t ** 6 + 0.000000000875 * t ** 7;
  }
  if (y < 1900) {
    t = y - 1860;
    return 7.62 + 0.5737 * t - 0.251754 * t ** 2 + 0.01680668 * t ** 3 - 0.0004473624 * t ** 4 + t ** 5 / 233174;
  }
  if (y < 1920) { t = y - 1900; return -2.79 + 1.494119 * t - 0.0598939 * t ** 2 + 0.0061966 * t ** 3 - 0.000197 * t ** 4; }
  if (y < 1941) { t = y - 1920; return 21.20 + 0.84493 * t - 0.076100 * t ** 2 + 0.0020936 * t ** 3; }
  if (y < 1961) { t = y - 1950; return 29.07 + 0.407 * t - t ** 2 / 233 + t ** 3 / 2547; }
  if (y < 1986) { t = y - 1975; return 45.45 + 1.067 * t - t ** 2 / 260 - t ** 3 / 718; }
  if (y < 2005) {
    t = y - 2000;
    return 63.86 + 0.3345 * t - 0.060374 * t ** 2 + 0.0017275 * t ** 3 + 0.000651814 * t ** 4 + 0.00002373599 * t ** 5;
  }
  if (y < 2050) { t = y - 2000; return 62.92 + 0.32217 * t + 0.005589 * t ** 2; }
  const u = (y - 1820) / 100;
  if (y < 2150) return -20 + 32 * u * u - 0.5628 * (2150 - y);
  return -20 + 32 * u * u;
}

export const yearOfJde = (jde) => 2000 + (jde - J2000) / 365.25;
export const utOfJde = (jde) => jde - deltaT(yearOfJde(jde)) / 86400;

