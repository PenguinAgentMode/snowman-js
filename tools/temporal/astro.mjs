function vsop(series, tau) {
  let sum = 0;
  series.forEach((terms, power) => {
    let s = 0;
    for (const [a, b, c] of terms) s += a * Math.cos(b + c * tau);
    sum += s * tau ** power;
  });
  return sum / 1e8;
}

// Heliocentric ecliptic longitude of the Earth (radians, VSOP87 dynamical frame) and radius vector (au).
export function earth(jde) {
  const tau = (jde - J2000) / 365250;
  return { L: vsop(EARTH_L, tau), R: vsop(EARTH_R, tau) };
}

// Nutation in longitude, degrees (Meeus chapter 22, the four largest terms).
export function nutationLongitude(jde) {
  const T = (jde - J2000) / 36525;
  const L = 280.4665 + 36000.7698 * T;
  const Lp = 218.3165 + 481267.8813 * T;
  const Om = 125.04452 - 1934.136261 * T + 0.0020708 * T ** 2 + T ** 3 / 450000;
  return (-17.20 * sinD(Om) - 1.32 * sinD(2 * L) - 0.23 * sinD(2 * Lp) + 0.21 * sinD(2 * Om)) / 3600;
}

// The Sun's apparent geocentric longitude in degrees, [0, 360).
export function sunLongitude(jde) {
  const { L, R } = earth(jde);
  const theta = L / D2R + 180 - 0.09033 / 3600;
  const lambda = theta + nutationLongitude(jde) - 20.4898 / 3600 / R;
  return ((lambda % 360) + 360) % 360;
}

// The JDE at which the Sun's apparent longitude is `degrees`, nearest to `guess` (within ~half a year).
export function solarLongitudeTime(degrees, guess) {
  let jde = guess;
  for (let i = 0; i < 20; i++) {
    let d = degrees - sunLongitude(jde);
    d -= 360 * Math.round(d / 360);
    const step = d * 365.2422 / 360;
    jde += step;
    if (Math.abs(step) < 1e-8) break;
  }
  return jde;
}
