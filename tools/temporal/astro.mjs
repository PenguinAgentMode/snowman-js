// The JDE of the true new moon of lunation k (k = 0: 2000-01-06).
export function newMoon(k) {
  const T = k / 1236.85;
  let jde = 2451550.09766 + 29.530588861 * k + 0.00015437 * T ** 2 - 0.000000150 * T ** 3 + 0.00000000073 * T ** 4;
  const E = 1 - 0.002516 * T - 0.0000074 * T ** 2;
  const M = 2.5534 + 29.10535670 * k - 0.0000014 * T ** 2 - 0.00000011 * T ** 3;
  const Mp = 201.5643 + 385.81693528 * k + 0.0107582 * T ** 2 + 0.00001238 * T ** 3 - 0.000000058 * T ** 4;
  const F = 160.7108 + 390.67050284 * k - 0.0016118 * T ** 2 - 0.00000227 * T ** 3 + 0.000000011 * T ** 4;
  const Om = 124.7746 - 1.56375588 * k + 0.0020672 * T ** 2 + 0.00000215 * T ** 3;
  for (const [c, e, m, mp, f, om] of NEW_MOON_TERMS) jde += c * E ** e * sinD(m * M + mp * Mp + f * F + om * Om);
  PLANETARY_TERMS.forEach(([c, a0, a1], i) => { jde += c * sinD(a0 + a1 * k - (i === 0 ? 0.009173 * T ** 2 : 0)); });
  return jde;
}

