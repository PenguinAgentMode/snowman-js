// flaky.mjs: the files whose result differs between repeated full-suite runs of one binary.
//
//   node tools/lead/flaky.mjs --label <sha> --out tools/lead/flaky.md name=run.jsonl name=run.jsonl ...
//
// A scenario (file + mode) differs if its status isn't the same in every run (a scenario missing from a run counts
// as "missing"). Each differing file is listed once, with status / ms / rss_mb / error of each run for every
// differing scenario, under one class, first match wins:
//   memory   a run ended in MemoryLimit (the runner's 700 MB resident or 86% machine guard);
//   timeout  a run timed out or took >= 8 s (the timeout is 10 s): for performance work;
//   crash    a failing run left no error line (killed by a signal, abort, no output) or says fatal/Segmentation:
//            for hardening;
//   other    everything else (e.g. a different error message).
import fs from 'node:fs';

const args = process.argv.slice(2);
const opt = (name) => (args.includes(name) ? args.splice(args.indexOf(name), 2)[1] : null);
const label = opt('--label');
const out = opt('--out');
const runs = args.map((a) => {
  const [name, file] = a.split('=');
  const rows = new Map();
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    if (!line) continue;
    const r = JSON.parse(line);
    rows.set(`${r.file}|${r.mode}`, r);
  }
  return { name, file, rows };
});

const SLOW_MS = 8000;
const keys = new Set(runs.flatMap((r) => [...r.rows.keys()]));
const byFile = new Map();
for (const key of keys) {
  const results = runs.map((r) => r.rows.get(key) ?? { status: 'missing' });
  if (new Set(results.map((x) => x.status)).size === 1) continue;
  const [file, mode] = key.split('|');
  if (!byFile.has(file)) byFile.set(file, []);
  byFile.get(file).push({ mode, results });
}

function classify(scenarios) {
  const all = scenarios.flatMap((s) => s.results);
  if (all.some((x) => x.error_name === 'MemoryLimit')) return 'memory';
  if (all.some((x) => x.status === 'timeout' || x.ms >= SLOW_MS)) return 'timeout';
  if (all.some((x) => x.status === 'fail' && (!x.error_name || /fatal|Segmentation|signal|abort/i.test(x.message ?? '')))) return 'crash';
  return 'other';
}

const classes = { timeout: [], crash: [], memory: [], other: [] };
for (const [file, scenarios] of [...byFile].sort(([a], [b]) => a.localeCompare(b))) classes[classify(scenarios)].push({ file, scenarios });

const cell = (x) => {
  if (x.status === 'missing') return 'missing';
  const error = x.error_name ? ` ${x.error_name}: ${String(x.message ?? '').slice(0, 90).replace(/\|/g, '\\|')}` : '';
  return `${x.status} ${x.ms} ms ${x.rss_mb ?? '?'} MB${error}`;
};
const passing = (r) => [...r.rows.values()].filter((x) => x.status === 'pass').length;
const lines = [
  `# Flaky files: main ${label}, ${runs.length} full-suite runs of one binary`,
  '',
  `Generated by \`node tools/lead/flaky.mjs --label ${label} --out tools/lead/flaky.md ${runs.map((r) => r.name + '=<jsonl>').join(' ')}\`.`,
  `A file is listed if any of its scenarios has a different status in any run (${byFile.size} files). Classes: memory`,
  `(MemoryLimit in a run), timeout (a timeout or >= ${SLOW_MS / 1000} s in a run; for perf), crash (a failing run with no`,
  'error line or a fatal/signal message; for hardening), other.',
  '',
  '| Run | JSONL | Scenarios | Passing |',
  '| --- | --- | --- | --- |',
  ...runs.map((r) => `| ${r.name} | ${r.file.replace(/^.*\/results\//, 'results/')} | ${r.rows.size} | ${passing(r)} |`),
  '',
  `Counts: timeout ${classes.timeout.length}, crash ${classes.crash.length}, memory ${classes.memory.length}, other ${classes.other.length}.`,
];
for (const [name, list] of Object.entries(classes)) {
  lines.push('', `## ${name} (${list.length})`);
  if (!list.length) continue;
  lines.push('', `| File | Mode | ${runs.map((r) => r.name).join(' | ')} |`, `| --- | --- | ${runs.map(() => '---').join(' | ')} |`);
  for (const { file, scenarios } of list) {
    for (const s of scenarios) lines.push(`| ${file.replace(/^test\//, '')} | ${s.mode} | ${s.results.map(cell).join(' | ')} |`);
  }
}
fs.writeFileSync(out, lines.join('\n') + '\n');
console.log(`files ${byFile.size}: timeout ${classes.timeout.length}, crash ${classes.crash.length}, memory ${classes.memory.length}, other ${classes.other.length}`);
