// Generates src/builtins/normalize_tables.inc from node's String.prototype.normalize: full canonical (NFD)
// and compatibility (NFKD) decompositions, canonical combining class ranks, and the primary composites.
// JS does not expose Canonical_Combining_Class, so ranks are recovered from how NFD reorders pairs of
// marks: normalization only compares classes (zero, equal, less), which ranks preserve. Hangul is
// algorithmic and left out. Run: node tools/runtime/gen-normalize.mjs > src/builtins/normalize_tables.inc
const cps = s => [...s].map(c => c.codePointAt(0));
const str = cp => String.fromCodePoint(cp);
const isHangul = cp => cp >= 0xac00 && cp <= 0xd7a3;
const all = [];
for (let cp = 0; cp <= 0x10ffff; cp++) if (cp < 0xd800 || cp > 0xdfff) all.push(cp);

const nfd = [], nfkd = [];
for (const cp of all) {
  if (isHangul(cp)) continue;
  const s = str(cp), d = s.normalize('NFD'), kd = s.normalize('NFKD');
  if (d !== s) nfd.push([cp, cps(d)]);
  if (kd !== s) nfkd.push([cp, cps(kd)]);
}

// Marks: code points that are their own NFD and have a nonzero class.
const reorders = (a, b) => (str(a) + str(b)).normalize('NFD') === str(b) + str(a);
const marks = all.filter(cp => !isHangul(cp) && str(cp).normalize('NFD') === str(cp) &&
                               (cp === 0x345 || reorders(0x345, cp) || reorders(cp, 0x334)));
marks.sort((a, b) => (reorders(a, b) ? 1 : reorders(b, a) ? -1 : 0));
const ccc = [];
let rank = 0, prev = -1;
for (const cp of marks) {
  if (prev < 0 || reorders(cp, prev)) rank++;
  ccc.push([cp, rank]);
  prev = cp;
}
ccc.sort((a, b) => a[0] - b[0]);

// Primary composites: canonically decomposable, kept by NFC. Their pair is found by splitting the NFD.
const compositions = [];
for (const [cp, d] of nfd) {
  if (str(cp).normalize('NFC') !== str(cp)) continue;
  for (let j = d.length - 1; j >= 1; j--) {
    const first = cps(String.fromCodePoint(...d.filter((_, i) => i !== j)).normalize('NFC'));
    if (first.length !== 1) continue;
    if ((str(first[0]) + str(d[j])).normalize('NFC') === str(cp)) {
      compositions.push([first[0], d[j], cp]);
      break;
    }
  }
}
compositions.sort((a, b) => a[0] - b[0] || a[1] - b[1]);

const hex = x => '0x' + x.toString(16);
function decompositionTable(name, list) {
  let pool = [], entries = [];
  for (const [cp, d] of list) {
    entries.push(`{${hex(cp)}, ${pool.length}, ${d.length}}`);
    pool.push(...d);
  }
  return `constexpr DecompositionEntry ${name}[] = {\n  ${entries.join(',\n  ')}};\n` +
         `constexpr char32_t ${name}Pool[] = {${pool.map(hex).join(', ')}};\n`;
}
console.log(`// Generated by tools/runtime/gen-normalize.mjs from node ${process.version} (Unicode ${process.versions.unicode}). Do not edit.`);
console.log(decompositionTable('kCanonicalDecomposition', nfd));
console.log(decompositionTable('kCompatibilityDecomposition', nfkd));
console.log(`constexpr CombiningClassEntry kCombiningClass[] = {\n  ${ccc.map(([c, r]) => `{${hex(c)}, ${r}}`).join(',\n  ')}};\n`);
console.log(`constexpr CompositionEntry kComposition[] = {\n  ${compositions.map(([a, b, c]) => `{${hex(a)}, ${hex(b)}, ${hex(c)}}`).join(',\n  ')}};`);
