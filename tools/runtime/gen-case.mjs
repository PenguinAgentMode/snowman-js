// Generates src/builtins/case_mapping.inc: the full, locale-independent toUpperCase / toLowerCase
// mappings (UnicodeData + unconditional SpecialCasing) as node reports them. Final_Sigma is handled in
// code. Run: node tools/runtime/gen-case.mjs > src/builtins/case_mapping.inc
const upper = [], lower = [];
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  const s = String.fromCodePoint(cp);
  const u = s.toUpperCase(), l = s.toLowerCase();
  if (u !== s) upper.push([cp, [...u].map(c => c.codePointAt(0))]);
  if (l !== s) lower.push([cp, [...l].map(c => c.codePointAt(0))]);
}
function emit(name, list) {
  let out = `// ${list.length} entries: {code point, mapping length, mapping}.\nconstexpr CaseEntry ${name}[] = {\n`;
  for (const [cp, m] of list) {
    const to = [...m, 0, 0, 0].slice(0, 3).map(x => '0x' + x.toString(16)).join(', ');
    out += `    {0x${cp.toString(16)}, ${m.length}, {${to}}},\n`;
  }
  return out + '};\n';
}
console.log(`// Generated by tools/runtime/gen-case.mjs from node ${process.version} (Unicode ${process.versions.unicode}). Do not edit.`);
console.log(emit('kUpperCase', upper));
console.log(emit('kLowerCase', lower));
